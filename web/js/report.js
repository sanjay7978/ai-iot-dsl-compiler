// report.js — a printable one-document compilation report (save it as PDF from the print dialog).

import { $, escapeHtml, toast } from "./util.js";
import { state, fresh } from "./state.js";
import { highlightDsl, irHtml, highlightCode } from "./highlight.js";
import { renderTree, renderCfg } from "./graph.js";

function table(head, rows) {
  return `<table class="r-table"><thead><tr>${head.map((h) => `<th>${h}</th>`).join("")}</tr></thead><tbody>${rows
    .map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join("")}</tr>`).join("")}</tbody></table>`;
}

const irBlock = (code) => `<pre class="r-code">${code.map((i) => (i.op === "rule" || i.op === "label" ? "" : "    ") + irHtml(i)).join("\n")}</pre>`;

export function printReport() {
  if (!fresh()) return toast("Compile the program first");
  const r = state.result;
  const ok = r.stats.errors === 0;
  const date = new Date().toLocaleString();
  const cats = {};
  r.tokens.forEach((t) => (cats[t.category] = (cats[t.category] || 0) + 1));

  const html = `
    <header class="r-head"><h1>IoT DSL Compiler — compilation report</h1>
      <p>${escapeHtml(state.exampleName || "Program")} · ${date} · ${ok ? "compiled successfully" : r.stats.errors + " error(s)"} · ${r.stats.timeMs.toFixed(2)} ms</p></header>
    <section><h2>1. Source program</h2><pre class="r-code">${highlightDsl(state.compiledSource)}</pre>
      ${r.english.length ? `<h3>In plain English (compiler back-translation)</h3>${r.english.map((s) => `<p>${escapeHtml(s)}</p>`).join("")}` : ""}</section>
    <section><h2>2. Compiler phases</h2>${table(["Phase", "Status"], r.phases.map((p) => [p.name, p.status]))}</section>
    <section><h2>3. Lexical analysis</h2><p>${r.tokens.length} tokens: ${Object.entries(cats).map(([k, v]) => `${v} ${k}`).join(", ")}.</p>
      ${table(["#", "Line:Col", "Token", "Lexeme"], r.tokens.slice(0, 60).map((t, i) => [i + 1, `${t.line}:${t.col}`, t.type, escapeHtml(t.lexeme)]))}
      ${r.tokens.length > 60 ? `<p>… ${r.tokens.length - 60} more tokens.</p>` : ""}</section>
    <section class="r-break"><h2>4. Abstract syntax tree</h2><div id="rTree" class="r-graph"></div></section>
    <section><h2>5. Semantic analysis</h2>${r.symbols.length ? table(["Name", "Kind", "Type", "Declared", "Uses"], r.symbols.map((s) => [escapeHtml(s.name), s.kind, s.type, `${s.line}:${s.col}`, s.uses])) : "<p>Not run.</p>"}
      <h3>Problems</h3>${r.errors.length ? table(["Phase", "Severity", "Line:Col", "Message"], r.errors.map((e) => [e.phase, e.severity, `${e.line}:${e.col}`, escapeHtml(e.message)])) : "<p>None.</p>"}</section>
    ${ok ? `
    <section class="r-break"><h2>6. Intermediate code</h2><div class="r-cols"><div><h3>Three-address code (${r.stats.irBefore})</h3>${irBlock(r.ir)}</div>
      <div><h3>Optimized (${r.stats.irAfter})</h3>${irBlock(r.optimizedIr)}</div></div>
      ${table(["Optimization pass", "Changes"], r.optimization.passes.filter((p) => p.count).map((p) => [p.name, p.count]))}</section>
    <section class="r-break"><h2>7. Control-flow graph (optimized code)</h2><div id="rCfg" class="r-graph"></div></section>
    <section class="r-break"><h2>8. Generated C</h2><pre class="r-code">${highlightCode(r.targets[0].code, "c")}</pre></section>` : ""}
    <footer class="r-foot">Generated by iotc, a hand-written C++ compiler for an IoT rule language.</footer>`;

  const host = $("report");
  host.innerHTML = html;
  if (r.ast) {
    const t = renderTree($("rTree"), r.ast);
    sizeForPrint($("rTree"), t);
  }
  if (ok) {
    const c = renderCfg($("rCfg"), r.cfg, r.optimizedIr);
    sizeForPrint($("rCfg"), c);
  }
  setTimeout(() => window.print(), 300);
}

// Printed graphs show the whole picture (no pan/zoom).
function sizeForPrint(container, view) {
  const svg = container.querySelector("svg");
  const g = svg.querySelector("g");
  requestAnimationFrame(() => {
    const box = g.getBBox();
    svg.setAttribute("viewBox", `${box.x - 10} ${box.y - 10} ${box.width + 20} ${box.height + 20}`);
    g.removeAttribute("transform");
    svg.style.height = Math.min(900, box.height + 20) + "px";
    const tools = container.querySelector(".graph-tools");
    if (tools) tools.remove();
  });
  return view;
}

// ai.js — the AI assistant: English -> DSL (typed or spoken), "Explain this program",
// per-problem explanations and AI fixes. Everything the AI writes is re-checked by iotc.

import { $, bus, escapeHtml, postJson, getJson, toast } from "./util.js";
import { state, fresh } from "./state.js";
import { highlightDsl } from "./highlight.js";
import { getSource } from "./editor.js";

let aiDsl = null;

export async function loadAiStatus() {
  try {
    const s = await getJson("/api/ai-status");
    const badge = $("aiBadge");
    badge.textContent = s.mode === "llm" ? `AI · ${s.provider} · ${s.model}` : "AI · offline rules";
    badge.classList.toggle("live", s.mode === "llm");
    badge.title = s.mode === "llm"
      ? "English is converted by a free language model; the result is checked by the compiler"
      : "No AI model is configured, so a built-in rule-based converter is used (see .env.example)";
  } catch (e) {
    $("aiBadge").textContent = "AI · unavailable";
  }
}

// ---- English -> DSL -------------------------------------------------------------------

async function convert(text) {
  const btn = $("aiBtn");
  btn.classList.add("busy");
  btn.disabled = true;
  btn.textContent = "Converting…";
  try {
    showAiResult(await postJson("/api/nl2dsl", { text, context: getSource() }));
  } catch (err) {
    showAiResult({ ok: false, error: err.message });
  } finally {
    btn.classList.remove("busy");
    btn.disabled = false;
    btn.textContent = "Convert to DSL";
  }
}

function showAiResult(d) {
  $("aiResult").hidden = false;
  $("aiNote").hidden = !d.note;
  $("aiNote").textContent = d.note || "";
  const canUse = d.ok && d.dsl;
  $("aiReplace").hidden = $("aiAppend").hidden = !canUse;
  if (!canUse) {
    aiDsl = null;
    $("aiCheck").className = "ai-check bad";
    $("aiCheck").textContent = "Couldn't convert this sentence";
    $("aiMeta").textContent = d.provider || "";
    $("aiCode").textContent = d.error || "Unknown error";
    return;
  }
  aiDsl = d.dsl;
  $("aiCheck").className = "ai-check " + (d.valid ? "ok" : "bad");
  $("aiCheck").textContent = d.valid
    ? "✓ Checked by the compiler: no errors"
    : `Compiler found ${d.errors.length} error${d.errors.length === 1 ? "" : "s"}: ${d.errors[0]}`;
  $("aiMeta").textContent = "Generated by " + d.provider + (d.model ? " · " + d.model : "") +
    (d.attempts > 1 ? " · repaired once using compiler errors" : "");
  $("aiCode").innerHTML = highlightDsl(d.dsl);
}

// Adds the AI output to the program, skipping declarations it already has.
export function mergeDsl(existing, generated) {
  const declared = new Set();
  existing.replace(/^\s*SENSOR\s+(\w+)/gm, (m, n) => declared.add(n));
  existing.replace(/^\s*DEVICE\s+(.+)$/gm, (m, l) => l.split(",").forEach((n) => declared.add(n.trim())));
  const out = [];
  for (const line of generated.split("\n")) {
    let m;
    if ((m = line.match(/^\s*SENSOR\s+(\w+)/))) {
      if (declared.has(m[1])) continue;
      declared.add(m[1]);
      out.push(line);
    } else if ((m = line.match(/^\s*DEVICE\s+(.+)$/))) {
      const names = m[1].split(",").map((s) => s.trim()).filter((n) => n && !declared.has(n));
      names.forEach((n) => declared.add(n));
      if (names.length) out.push("DEVICE " + names.join(", "));
    } else {
      out.push(line);
    }
  }
  const addition = out.join("\n").replace(/^\s+/, "");
  return existing.trim() ? existing.replace(/\s*$/, "") + "\n\n" + addition : addition;
}

// ---- voice input (Web Speech API) ------------------------------------------------------

function initVoice() {
  const Rec = window.SpeechRecognition || window.webkitSpeechRecognition;
  const mic = $("aiMic");
  if (!Rec) { mic.hidden = true; return; }
  let rec = null;
  mic.addEventListener("click", () => {
    if (rec) { rec.stop(); return; }
    rec = new Rec();
    rec.lang = navigator.language || "en-US";
    rec.interimResults = true;
    rec.maxAlternatives = 1;
    mic.classList.add("listening");
    mic.setAttribute("aria-pressed", "true");
    $("aiInput").placeholder = "Listening… say a rule, e.g. “if the temperature is above 30 turn on the fan”";
    let finalText = "";
    rec.onresult = (e) => {
      let interim = "";
      for (let i = e.resultIndex; i < e.results.length; i++) {
        if (e.results[i].isFinal) finalText += e.results[i][0].transcript;
        else interim += e.results[i][0].transcript;
      }
      $("aiInput").value = (finalText + interim).trim();
    };
    rec.onerror = (e) => toast(e.error === "not-allowed" ? "Microphone permission was denied" : "Voice input error: " + e.error, "bad");
    rec.onend = () => {
      mic.classList.remove("listening");
      mic.setAttribute("aria-pressed", "false");
      $("aiInput").placeholder = "e.g. If the temperature is above 30 and the door is open, turn on the fan";
      rec = null;
      if (finalText.trim()) convert(finalText.trim());
    };
    rec.start();
  });
}

// ---- explain this program --------------------------------------------------------------

export function showEnglish() {
  const card = $("englishCard");
  const r = state.result;
  if (!r || !r.english || !r.english.length) {
    card.hidden = false;
    $("englishText").innerHTML = "<p>Compile a program without syntax errors first.</p>";
    $("englishBy").textContent = "";
    return;
  }
  card.hidden = false;
  $("englishText").innerHTML = r.english.map((s) => `<p>${escapeHtml(s)}</p>`).join("");
  $("englishBy").textContent = "Written by the compiler (AST → English back-translation), no AI needed";
}

async function friendlier() {
  const btn = $("englishAi");
  btn.disabled = true;
  btn.textContent = "Asking the AI…";
  try {
    const d = await postJson("/api/explain-program", { source: state.compiledSource, english: state.result.english });
    $("englishText").innerHTML = d.text.split(/\n+/).map((p) => `<p>${escapeHtml(p)}</p>`).join("");
    $("englishBy").textContent = "Explained by " + d.provider;
  } catch (e) {
    toast("Could not get an AI explanation: " + e.message, "bad");
  } finally {
    btn.disabled = false;
    btn.textContent = "Make it friendlier (AI)";
  }
}

// ---- problems: explain and AI fix ------------------------------------------------------

async function explainProblem({ item, index, button }) {
  let box = item.querySelector(".explanation");
  if (box) { box.remove(); button.textContent = "Explain"; return; }
  box = document.createElement("div");
  box.className = "explanation";
  box.textContent = "Asking the AI assistant…";
  item.appendChild(box);
  button.textContent = "Hide";
  try {
    const d = state.explanations[index] ||
      (state.explanations[index] = await postJson("/api/explain", { source: state.compiledSource, error: state.result.errors[index] }));
    box.textContent = d.text;
    const by = document.createElement("span");
    by.className = "by";
    by.textContent = "Explained by " + d.provider;
    box.appendChild(by);
  } catch (e) {
    box.textContent = "Could not get an explanation: " + e.message;
  }
}

function lineDiff(a, b) {
  const x = a.split("\n"), y = b.split("\n");
  const n = x.length, m = y.length;
  const dp = Array.from({ length: n + 1 }, () => new Uint16Array(m + 1));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) dp[i][j] = x[i] === y[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
  const out = [];
  let i = 0, j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && x[i] === y[j]) { i++; j++; continue; }
    if (j < m && (i >= n || dp[i][j + 1] >= dp[i + 1][j])) out.push(`<div class="d-add">+ ${escapeHtml(y[j++])}</div>`);
    else out.push(`<div class="d-del">− ${escapeHtml(x[i++])}</div>`);
  }
  return out.join("") || '<div class="d-same">(no change)</div>';
}

async function aiFix({ item, index, button }) {
  let box = item.querySelector(".ai-fix-box");
  if (box) { box.remove(); return; }
  box = document.createElement("div");
  box.className = "ai-fix-box";
  box.textContent = "Asking the AI for a fix, then checking it with the compiler…";
  item.appendChild(box);
  button.disabled = true;
  try {
    const d = await postJson("/api/fix", { source: state.compiledSource, error: state.result.errors[index] });
    if (!d.ok) throw new Error(d.error);
    box.innerHTML = `<div class="ai-fix-head">Suggested by ${escapeHtml(d.provider)} · checked by the compiler: errors ${d.errorsBefore} → ${d.errorsAfter}</div>` +
      `<div class="diff">${lineDiff(state.compiledSource, d.source)}</div>` +
      '<div class="ai-actions"><button type="button" class="btn btn-small btn-primary">Apply fix</button><button type="button" class="link-btn">Dismiss</button></div>';
    box.querySelector(".btn-primary").addEventListener("click", () => bus.emit("replace-source", d.source));
    box.querySelector(".link-btn").addEventListener("click", () => box.remove());
  } catch (e) {
    box.textContent = e.message;
  } finally {
    button.disabled = false;
  }
}

export function initAi() {
  $("aiForm").addEventListener("submit", (e) => {
    e.preventDefault();
    const text = $("aiInput").value.trim();
    if (!text) return $("aiInput").focus();
    convert(text);
  });
  $("aiReplace").addEventListener("click", () => { if (aiDsl) { bus.emit("replace-source", aiDsl); $("aiResult").hidden = true; } });
  $("aiAppend").addEventListener("click", () => { if (aiDsl) { bus.emit("replace-source", mergeDsl(getSource(), aiDsl)); $("aiResult").hidden = true; } });
  $("aiDismiss").addEventListener("click", () => ($("aiResult").hidden = true));
  $("explainBtn").addEventListener("click", () => {
    if ($("englishCard").hidden || !fresh()) showEnglish();
    else $("englishCard").hidden = true;
  });
  $("englishAi").addEventListener("click", friendlier);
  $("englishClose").addEventListener("click", () => ($("englishCard").hidden = true));
  bus.on("explain-problem", explainProblem);
  bus.on("ai-fix", aiFix);
  bus.on("compiled", () => { if (!$("englishCard").hidden) showEnglish(); });
  initVoice();
  loadAiStatus();
}
